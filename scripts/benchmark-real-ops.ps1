param(
    [switch]$Network
)

$ErrorActionPreference = "Stop"
$PSNativeCommandUseErrorActionPreference = $true

$Root = Split-Path -Parent $PSScriptRoot
$Forge = Join-Path $Root "target\release\forge.exe"
$Work = Join-Path $Root "target\bench-real"
$Fixtures = Join-Path $Work "fixtures"
$Out = Join-Path $Work "out"
$Json = Join-Path $Work "benchmark-real-ops.json"
$Md = Join-Path $Root "docs\benchmark-results.md"

function New-CleanDir($Path) {
    if (Test-Path $Path) {
        Remove-Item -LiteralPath $Path -Recurse -Force
    }
    New-Item -ItemType Directory -Force $Path | Out-Null
}

function Measure-Case($Name, [scriptblock]$ForgeCommand, [scriptblock]$DirectCommand) {
    $forgeRuns = 1..3 | ForEach-Object { (Measure-Command $ForgeCommand).TotalMilliseconds }
    $directRuns = 1..3 | ForEach-Object { (Measure-Command $DirectCommand).TotalMilliseconds }
    [pscustomobject]@{
        name = $Name
        forge_avg_ms = [math]::Round(($forgeRuns | Measure-Object -Average).Average, 1)
        direct_avg_ms = [math]::Round(($directRuns | Measure-Object -Average).Average, 1)
        forge_min_ms = [math]::Round(($forgeRuns | Measure-Object -Minimum).Minimum, 1)
        direct_min_ms = [math]::Round(($directRuns | Measure-Object -Minimum).Minimum, 1)
    }
}

Push-Location $Root
try {
    cargo build --release --workspace | Out-Host
    New-CleanDir $Work
    New-Item -ItemType Directory -Force $Fixtures, $Out | Out-Null

    ffmpeg -hide_banner -v error -y -f lavfi -i testsrc=size=640x360:rate=24 -f lavfi -i sine=frequency=440:sample_rate=44100 -t 3 -pix_fmt yuv420p (Join-Path $Fixtures "video.mp4") | Out-Host
    ffmpeg -hide_banner -v error -y -f lavfi -i testsrc=size=640x360:rate=24 -f lavfi -i sine=frequency=660:sample_rate=44100 -t 3 -pix_fmt yuv420p (Join-Path $Fixtures "video.mov") | Out-Host
    ffmpeg -hide_banner -v error -y -f lavfi -i sine=frequency=880:sample_rate=44100 -t 3 (Join-Path $Fixtures "audio.wav") | Out-Host

    $video = Join-Path $Fixtures "video.mp4"
    $mov = Join-Path $Fixtures "video.mov"
    $wav = Join-Path $Fixtures "audio.wav"

    $cases = @()
    $cases += Measure-Case "inspect video" {
        & $Forge --json inspect $video | Out-Null
    } {
        ffprobe -v error -print_format json -show_format -show_streams $video | Out-Null
    }
    $cases += Measure-Case "convert mov to mp4" {
        & $Forge --output (Join-Path $Out "forge-convert-mp4-$_") convert $mov --to mp4 | Out-Null
    } {
        ffmpeg -hide_banner -v error -y -i $mov -c:v libx264 -c:a aac -movflags +faststart (Join-Path $Out "direct-convert-$_.mp4") | Out-Null
    }
    $cases += Measure-Case "convert wav to mp3" {
        & $Forge --output (Join-Path $Out "forge-convert-mp3-$_") convert $wav --to mp3 | Out-Null
    } {
        ffmpeg -hide_banner -v error -y -i $wav -vn -c:a libmp3lame "-q:a" 2 (Join-Path $Out "direct-convert-$_.mp3") | Out-Null
    }
    $cases += Measure-Case "clip video" {
        & $Forge --output (Join-Path $Out "forge-clip-$_") clip $video --range 00:00:00..00:00:01 | Out-Null
    } {
        ffmpeg -hide_banner -v error -y -ss 00:00:00 -to 00:00:01 -i $video -c copy (Join-Path $Out "direct-clip-$_.mp4") | Out-Null
    }
    $cases += Measure-Case "resize video" {
        & $Forge --output (Join-Path $Out "forge-resize-$_") resize $video --width 320 | Out-Null
    } {
        ffmpeg -hide_banner -v error -y -i $video -vf scale=320:-2 -c:a copy (Join-Path $Out "direct-resize-$_.mp4") | Out-Null
    }
    $cases += Measure-Case "thumbnail at" {
        & $Forge --output (Join-Path $Out "forge-thumb-$_") thumbnail $video --at 00:00:01 | Out-Null
    } {
        ffmpeg -hide_banner -v error -y -ss 00:00:01 -i $video "-frames:v" 1 "-q:v" 2 (Join-Path $Out "direct-thumb-$_.jpg") | Out-Null
    }
    $cases += Measure-Case "audio extract" {
        & $Forge --output (Join-Path $Out "forge-audio-$_") audio $video --extract | Out-Null
    } {
        ffmpeg -hide_banner -v error -y -i $video -vn -c:a libmp3lame "-q:a" 2 (Join-Path $Out "direct-audio-$_.mp3") | Out-Null
    }

    if ($Network) {
        $url = "https://archive.org/details/SampleVideo1280x7205mb"
        $cases += Measure-Case "youtube metadata simulate" {
            & $Forge --output (Join-Path $Out "forge-youtube-$_") youtube $url --metadata --simulate | Out-Null
        } {
            yt-dlp --paths (Join-Path $Out "direct-youtube-$_") --simulate --write-info-json $url | Out-Null
        }
    }

    $cases | ConvertTo-Json -Depth 4 | Set-Content -Encoding UTF8 -LiteralPath $Json

    $lines = @(
        "# Benchmark results",
        "",
        "Generated by `scripts/benchmark-real-ops.ps1` on this Windows machine.",
        "",
        "| Operation | Forgy avg | Direct backend avg | Delta |",
        "| --- | ---: | ---: | ---: |"
    )
    foreach ($case in $cases) {
        $delta = [math]::Round($case.forge_avg_ms - $case.direct_avg_ms, 1)
        $lines += "| $($case.name) | $($case.forge_avg_ms) ms | $($case.direct_avg_ms) ms | $delta ms |"
    }
    $lines += ""
    $lines += "Interpretation: Forgy adds planning, output-folder creation, terminal UX, and report files on top of the backend command. The benchmark compares full command execution, not help text."
    $lines | Set-Content -Encoding UTF8 -LiteralPath $Md

    $cases | Format-Table -AutoSize
    "Benchmark JSON: $Json"
    "Benchmark doc: $Md"
}
finally {
    Pop-Location
}
